#!/usr/bin/env python3
"""Pack each room's shell and stamps into one atlas. Pixels stay put."""
import re
from pathlib import Path
from PIL import Image

ROOT = Path(__file__).resolve().parents[2]
ART = ROOT / "public" / "art" / "rooms"
SRC = (ROOT / "src/game/roomArt.ts").read_text()
rooms = re.findall(r"^\s{2}(\w+): \[$", SRC, re.M)


def stamps_of(rid):
    m = re.search(rf"{rid}: \[(.*?)\],", SRC, re.S)
    out = []
    if not m:
        return out
    for src, x, y, foot, kind in re.findall(
        r'src: "([^"]+)", x: (-?\d+), y: (-?\d+), foot: (-?\d+), kind: "([^"]+)"',
        m.group(1),
    ):
        out.append((src.split("?")[0], int(x), int(y), int(foot), kind))
    return out


def pack(rid):
    shell = Image.open(ART / rid / "shell.png").convert("RGBA")
    items = []
    for src, x, y, foot, kind in stamps_of(rid):
        im = Image.open(ROOT / "public" / src.lstrip("/")).convert("RGBA")
        items.append((im, x, y, foot, kind))
    x0 = shell.width
    y0 = 0
    col_w = 0
    placed = []
    for im, x, y, foot, kind in items:
        if y0 > 0 and y0 + im.height > shell.height:
            x0 += col_w
            y0 = 0
            col_w = 0
        placed.append((im, x0, y0, x, y, foot, kind))
        col_w = max(col_w, im.width)
        y0 += im.height
    aw = x0 + col_w if placed else shell.width
    ah = shell.height
    atlas = Image.new("RGBA", (aw, ah), (0, 0, 0, 0))
    atlas.paste(shell, (0, 0))
    meta = []
    for im, sx, sy, x, y, foot, kind in placed:
        atlas.alpha_composite(im, (sx, sy))
        meta.append({"kind": kind, "x": x, "y": y, "foot": foot, "sx": sx, "sy": sy, "sw": im.width, "sh": im.height})
    # prove the atlas redraws the room
    back = Image.new("RGBA", shell.size, (0, 0, 0, 0))
    back.alpha_composite(atlas.crop((0, 0, shell.width, shell.height)))
    for st in meta:
        back.alpha_composite(atlas.crop((st["sx"], st["sy"], st["sx"] + st["sw"], st["sy"] + st["sh"])), (st["x"], st["y"]))
    ref = shell.copy()
    for im, _sx, _sy, x, y, _foot, _kind in placed:
        ref.alpha_composite(im, (x, y))
    n = 0
    a, b = back.load(), ref.load()
    for yy in range(shell.height):
        for xx in range(shell.width):
            if a[xx, yy] != b[xx, yy]:
                n += 1
    if n:
        raise SystemExit(f"{rid} atlas drifted by {n}px")
    atlas.save(ART / rid / "atlas.png")
    (ART / rid / "atlas.json").write_text(
        __import__("json").dumps({"src": f"/art/rooms/{rid}/atlas.png", "w": shell.width, "h": shell.height, "stamps": meta})
    )
    print(rid, atlas.size, "stamps", len(meta))
    return meta


def main():
    lines = [
        "/** Generated by tools/roomkit/pack_atlas.py. One sheet per room. */",
        "export type AtlasStamp = { kind: string; x: number; y: number; foot: number; sx: number; sy: number; sw: number; sh: number };",
        "export const ROOM_ATLAS: Record<string, { src: string; stamps: AtlasStamp[] }> = {",
    ]
    for rid in rooms:
        meta = pack(rid)
        lines.append(f'  {rid}: {{ src: "/art/rooms/{rid}/atlas.png", stamps: [')
        for st in meta:
            lines.append(
                f'    {{ kind: "{st["kind"]}", x: {st["x"]}, y: {st["y"]}, foot: {st["foot"]}, sx: {st["sx"]}, sy: {st["sy"]}, sw: {st["sw"]}, sh: {st["sh"]} }},'
            )
        lines.append("  ] },")
    lines.append("};")
    (ROOT / "src/game/roomAtlas.ts").write_text("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
