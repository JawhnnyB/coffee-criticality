export function AppGlyph({ id }: { id: string }) {
  const rows = GLYPHS[id] ?? GLYPHS.fallback;
  const dots: { x: number; y: number }[] = [];
  for (let y = 0; y < rows.length; y++) {
    const row = rows[y];
    for (let x = 0; x < row.length; x++) if (row[x] === "#") dots.push({ x, y });
  }
  return (
    <svg width="32" height="32" viewBox="0 0 16 16" aria-hidden className="app-glyph" shapeRendering="crispEdges">
      {dots.map((d, i) => (
        <rect key={i} x={d.x} y={d.y} width="1" height="1" fill="currentColor" />
      ))}
    </svg>
  );
}
